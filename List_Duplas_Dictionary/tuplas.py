'''¿Qué son las Tuplas?
Una tupla es una colección ordenada e inmutable de elementos en Python. Esto significa dos cosas clave:

Ordenada: Los elementos en una tupla tienen un orden definido, y ese orden no cambiará. Puedes acceder a los elementos por su posición (índice), al igual que en las listas.

Inmutable: Una vez que creas una tupla, no puedes cambiar, añadir o eliminar sus elementos. Si necesitas una versión modificada, tendrás que crear una tupla nueva.

Las tuplas se definen utilizando paréntesis () y los elementos se separan por comas.'''

